// 1. DYNAMIC SUBFOLDER CREATOR
// ==========================================
router.post('/create-permit-folders', requireAuth, async (req, res) => {
  try {
    const { permitNumber, applicantName, categories } = req.body;
    const rootFolderId = process.env.GOOGLE_DRIVE_FOLDER_ID;

    if (!rootFolderId) {
      return res.status(500).json({ 
        success: false, 
        message: 'Server Configuration Error: GOOGLE_DRIVE_FOLDER_ID missing on Render.' 
      });
    }

    const { drive } = getGoogleDriveClient();

    const getOrCreateFolder = async (folderName, parentId) => {
      const escapedName = folderName.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
      const q = `mimeType='application/vnd.google-apps.folder' and name='${escapedName}' and '${parentId}' in parents and trashed=false`;
      
      try {
        const searchRes = await drive.files.list({
          q: q,
          fields: 'files(id, name)',
          spaces: 'drive',
          pageSize: 10
        });

        if (searchRes.data.files && searchRes.data.files.length > 0) {
          return searchRes.data.files[0].id;
        }
      } catch (searchErr) {
        console.error("Folder search query warning:", searchErr.message);
      }

      const createRes = await drive.files.create({
        requestBody: {
          name: folderName,
          mimeType: 'application/vnd.google-apps.folder',
          parents: [parentId]
        },
        fields: 'id'
      });

      return createRes.data.id;
    };

    const cleanPermitNum = (permitNumber || '').replace(/[\/\\]/g, '_').trim();
    const cleanApplicant = (applicantName || '').replace(/[\/\\]/g, '-').trim();

    const masterFolderName = cleanApplicant 
      ? `${cleanPermitNum} - ${cleanApplicant}` 
      : cleanPermitNum;

    const masterFolderId = await getOrCreateFolder(masterFolderName, rootFolderId);

    try {
      await drive.permissions.create({
        fileId: masterFolderId,
        requestBody: {
          role: 'reader',
          type: 'anyone'
        }
      });
    } catch (permErr) {
      console.warn("Notice: Master folder permission setting skipped or already public:", permErr.message);
    }

    const categoryMap = {
      certificate: '1. Permit Certificates',
      drawings: '2. Architectural Drawings',
      permitForm: '3. Permit Forms',
      receipts: '4. Receipts & Bills'
    };

    const subfolders = {};
    const requestedCategories = Array.isArray(categories) && categories.length > 0 
      ? categories 
      : Object.keys(categoryMap);

    for (const cat of requestedCategories) {
      if (categoryMap[cat]) {
        subfolders[cat] = await getOrCreateFolder(categoryMap[cat], masterFolderId);
      }
    }

    res.json({
      success: true,
      masterFolderId,
      subfolders
    });

  } catch (err) {
    console.error("Folder structure creation error:", err);
    res.status(500).json({ success: false, message: `Folder Creation Error: ${err.message}` });
  }
});

