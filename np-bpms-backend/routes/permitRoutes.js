// 1. SINGLE MASTER FOLDER & SUBFOLDERS CREATOR (WITH ESCAPED SEARCH)
// ==========================================
router.post('/create-permit-folders', requireAuth, async (req, res) => {
  try {
    const { permitNumber, applicantName } = req.body;

    const clientId = process.env.GOOGLE_CLIENT_ID;
    const clientSecret = process.env.GOOGLE_CLIENT_SECRET;
    const refreshToken = process.env.GOOGLE_REFRESH_TOKEN;
    const rootFolderId = process.env.GOOGLE_DRIVE_FOLDER_ID;

    if (!clientId || !clientSecret || !refreshToken || !rootFolderId) {
      return res.status(500).json({ 
        success: false, 
        message: 'Server Configuration Error: Google OAuth keys missing on Render.' 
      });
    }

    const oauth2Client = new google.auth.OAuth2(
      clientId,
      clientSecret,
      process.env.GOOGLE_REDIRECT_URI || 'https://developers.google.com/oauthplayground'
    );

    oauth2Client.setCredentials({ refresh_token: refreshToken });
    const drive = google.drive({ version: 'v3', auth: oauth2Client });

    // Helper: Find or create Google Drive Folder with strict quote escaping
    const getOrCreateFolder = async (folderName, parentId) => {
      const escapedName = folderName.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
      const q = `mimeType='application/vnd.google-apps.folder' and name='${escapedName}' and '${parentId}' in parents and trashed=false`;
      
      try {
        const searchRes = await drive.files.list({
          q: q,
          fields: 'files(id, name)',
          spaces: 'drive',
          pageSize: 10
        });

        if (searchRes.data.files && searchRes.data.files.length > 0) {
          // Folder already exists! Return its ID
          return searchRes.data.files[0].id;
        }
      } catch (searchErr) {
        console.error("Folder search query warning:", searchErr.message);
      }

      // Create new folder if not found
      const createRes = await drive.files.create({
        requestBody: {
          name: folderName,
          mimeType: 'application/vnd.google-apps.folder',
          parents: [parentId]
        },
        fields: 'id'
      });

      return createRes.data.id;
    };

    // Format single master folder name: NIPDA_TSOP_26_02 - Applicant Name
    const cleanPermitNum = (permitNumber || '').replace(/[\/\\]/g, '_').trim();
    const cleanApplicant = (applicantName || '').replace(/[\/\\]/g, '-').trim();

    const masterFolderName = cleanApplicant 
      ? `${cleanPermitNum} - ${cleanApplicant}` 
      : cleanPermitNum;

    // A. Create/Fetch Exactly ONE Master Permit Folder
    const masterFolderId = await getOrCreateFolder(masterFolderName, rootFolderId);

    // B. Create/Fetch All 4 Subfolders Inside the Master Folder
    const certFolderId = await getOrCreateFolder('1. Permit Certificates', masterFolderId);
    const drawingsFolderId = await getOrCreateFolder('2. Architectural Drawings', masterFolderId);
    const formFolderId = await getOrCreateFolder('3. Permit Forms', masterFolderId);
    const receiptsFolderId = await getOrCreateFolder('4. Receipts & Bills', masterFolderId);

    res.json({
      success: true,
      masterFolderId,
      subfolders: {
        certificate: certFolderId,
        drawings: drawingsFolderId,
        permitForm: formFolderId,
        receipts: receiptsFolderId
      }
    });

  } catch (err) {
    console.error("Folder structure creation error:", err);
    res.status(500).json({ success: false, message: `Folder Creation Error: ${err.message}` });
  }
});

