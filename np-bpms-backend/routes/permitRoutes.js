// --- ENSURE SUPABASE PERMITS TABLE & AUTO-FIX STATUS ---
const ensureTablesExist = async () => {
  try {
    await db.query(`
      CREATE TABLE IF NOT EXISTS permits (
        id bigint generated by default as identity not null,
        created_at timestamp with time zone not null default timezone ('utc'::text, now()),
        permit_number text not null,
        date_issued text not null,
        purpose text not null,
        applicant_name text not null,
        phone text null,
        address text not null,
        location text not null,
        certificate_link text null,
        drawings_links text null,
        permit_form_link text null,
        receipts_links text null,
        upload_status text null default 'completed'::text,
        status character varying(50) null default 'Synced'::character varying,
        constraint permits_pkey primary key (id)
      );
    `);

    await db.query(`ALTER TABLE permits ADD COLUMN IF NOT EXISTS upload_status text DEFAULT 'completed';`);
    await db.query(`ALTER TABLE permits ADD COLUMN IF NOT EXISTS status VARCHAR(50) DEFAULT 'Synced';`);

    // Convert any legacy pending/processing records to Synced
    await db.query(`
      UPDATE permits 
      SET status = 'Synced', upload_status = 'completed' 
      WHERE status IS NULL OR LOWER(status) = 'processing' OR LOWER(upload_status) = 'pending';
    `);

  } catch (err) {
    console.error("Error verifying Supabase permits table structure:", err);
  }
};

// --- JWT OFFICER AUTHENTICATION MIDDLEWARE ---
const requireAuth = (req, res, next) => {
  const authHeader = req.headers['authorization'];

  if (authHeader && authHeader.startsWith('Bearer ')) {
    const token = authHeader.split(' ')[1];
    try {
      const decoded = jwt.verify(token, process.env.JWT_SECRET || 'nipda_secret_key_2026');
      req.user = decoded;
      return next();
    } catch (err) {
      return res.status(401).json({ 
        success: false, 
        message: "Unauthorized: Invalid or expired session token. Please log in again." 
      });
    }
  }

  return res.status(401).json({ 
    success: false, 
    message: "Unauthorized: Officer session token required." 
  });
};

